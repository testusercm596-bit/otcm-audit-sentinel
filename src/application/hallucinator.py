@dataclass
class DefenseContext:
    """
    Defense context generated by the Hallucinator Agent
    
    Attributes:
        justification: Benign explanation for the security alert
        confidence: Confidence score (0.0 to 1.0) in the defense
        supporting_evidence: List of evidence points supporting the defense
        risk_mitigation: Suggested actions to mitigate any remaining risk
    """
    justification: str
    confidence: float
    supporting_evidence: Optional[List[str]] = None
    risk_mitigation: Optional[str] = None


class HallucinatorAgent:
    """
    Hallucinator Agent acts as a 'Defense Attorney' for security alerts
    
    This agent uses AI to generate benign justifications for security alerts,
    helping to reduce false positives by finding legitimate explanations for
    potentially suspicious behavior.
    
    The agent analyzes:
    - The security alert details
    - User's historical behavior patterns
    - Contextual information
    
    And attempts to construct a reasonable, benign explanation.
    """
    
    def __init__(self, model: str = "gpt-4", temperature: float = 0.7):
        """
        Initialize Hallucinator Agent
        
        Args:
            model: LLM model to use (default: gpt-4)
            temperature: Temperature for LLM generation (0.0-1.0)
        """
        self.model = model
        self.temperature = temperature
    
    def generate_defense(self, alert: Dict, user_history: List[Dict]) -> DefenseContext:
        """
        Generate a benign justification for a security alert
        
        Args:
            alert: Security alert dictionary containing:
                - is_alert: Whether alert was triggered
                - risk_score: Risk score of the alert
                - reason: Reason for the alert
                - event: The event that triggered the alert
                
            user_history: List of user's historical events/behaviors
        
        Returns:
            DefenseContext with justification and confidence score
        """
        # Construct the defense attorney prompt
        prompt = self._construct_defense_prompt(alert, user_history)
        
        # Call LLM to generate defense
        llm_response = self._call_llm(prompt)
        
        # Parse the response into DefenseContext
        defense_context = self._parse_llm_response(llm_response)
        
        return defense_context
    
    def _construct_defense_prompt(self, alert: Dict, user_history: List[Dict]) -> str:
        """
        Construct the system prompt for the defense attorney LLM
        
        Args:
            alert: Security alert details
            user_history: User's historical behavior
            
        Returns:
            Formatted prompt string
        """
        # Extract alert details
        risk_score = alert.get('risk_score', 0.0)
        reason = alert.get('reason', 'Unknown reason')
        event = alert.get('event', {})
        
        # Format user history
        history_summary = self._format_user_history(user_history)
        
        # Format event details
        event_details = self._format_event(event)
        
        # Construct the prompt
        prompt = f"""You are an expert Security Defense Attorney analyzing potential false positives in security alerts.

Your role is to find BENIGN, LEGITIMATE explanations for security alerts by considering:
1. The user's normal behavior patterns
2. Business context and workflows
3. Temporal patterns (time of day, day of week)
4. System events or maintenance activities
5. Legitimate use cases that may appear suspicious

SECURITY ALERT:
Risk Score: {risk_score}/1.0
Reason: {reason}

EVENT DETAILS:
{event_details}

USER HISTORICAL BEHAVIOR:
{history_summary}

TASK:
Analyze this alert and provide a benign justification if one exists. Consider:
- Is this behavior consistent with the user's normal patterns?
- Could this be a legitimate business activity?
- Are there external factors (maintenance, system updates, deadlines) that explain this?
- What context might make this behavior reasonable?

Respond in JSON format with:
{{
    "justification": "Clear, concise benign explanation",
    "confidence": 0.0-1.0 (how confident you are in this defense),
    "supporting_evidence": ["Evidence point 1", "Evidence point 2", ...],
    "risk_mitigation": "Suggested actions to verify or mitigate any remaining risk"
}}

If you CANNOT find a reasonable benign explanation, set confidence to 0.0 and explain why the alert remains suspicious."""

        return prompt
    
    def _format_user_history(self, user_history: List[Dict]) -> str:
        """Format user history for the prompt"""
        if not user_history:
            return "No historical data available."
        
        lines = []
        for i, event in enumerate(user_history[-10:], 1):  # Last 10 events
            event_type = event.get('event_type', event.get('event', 'UNKNOWN'))
            timestamp = event.get('timestamp', 'unknown time')
            record_type = event.get('record_type', 'unknown')
            
            lines.append(f"{i}. {timestamp}: {event_type} on {record_type}")
        
        return "\n".join(lines)
    
    def _format_event(self, event: Dict) -> str:
        """Format event details for the prompt"""
        if not event:
            return "No event details available."
        
        details = []
        
        if 'user_id' in event:
            details.append(f"User: {event['user_id']}")
        if 'event_type' in event or 'event' in event:
            details.append(f"Action: {event.get('event_type', event.get('event'))}")
        if 'timestamp' in event:
            details.append(f"Time: {event['timestamp']}")
        if 'record_type' in event:
            details.append(f"Record Type: {event['record_type']}")
        if 'record_title' in event:
            details.append(f"Record: {event['record_title']}")
        if 'metadata' in event:
            details.append(f"Metadata: {json.dumps(event['metadata'])}")
        
        return "\n".join(details)
    
