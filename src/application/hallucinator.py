    def _parse_llm_response(self, llm_response: str) -> DefenseContext:
        """
        Parse LLM response into DefenseContext object
        
        Args:
            llm_response: JSON string from LLM
            
        Returns:
            DefenseContext object
        """
        try:
            data = json.loads(llm_response)
            
            return DefenseContext(
                justification=data.get('justification', 'No justification provided'),
                confidence=float(data.get('confidence', 0.0)),
                supporting_evidence=data.get('supporting_evidence', []),
                risk_mitigation=data.get('risk_mitigation', 'No mitigation suggested')
            )
        except (json.JSONDecodeError, ValueError) as e:
            # Fallback if JSON parsing fails
            return DefenseContext(
                justification="Error parsing LLM response",
                confidence=0.0,
                supporting_evidence=[f"Parse error: {str(e)}"],
                risk_mitigation="Manual review required"
            )
    
    def batch_generate_defenses(self, alerts: List[Dict], user_history: Dict[str, List[Dict]]) -> List[DefenseContext]:
        """
        Generate defenses for multiple alerts
        
        Args:
            alerts: List of security alerts
            user_history: Dictionary mapping user_id to their history
            
        Returns:
            List of DefenseContext objects
        """
        defenses = []
        
        for alert in alerts:
            user_id = alert.get('event', {}).get('user_id', 'unknown')
            history = user_history.get(user_id, [])
            
            defense = self.generate_defense(alert, history)
            defenses.append(defense)
        
        return defenses
    
    def should_dismiss_alert(self, defense: DefenseContext, confidence_threshold: float = 0.7) -> bool:
        """
        Determine if alert should be dismissed based on defense confidence
        
        Args:
            defense: Defense context
            confidence_threshold: Minimum confidence to dismiss alert
            
        Returns:
            True if alert should be dismissed, False otherwise
        """
        return defense.confidence >= confidence_threshold
